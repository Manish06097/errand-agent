"""Reject AI-tool authorship attribution in commit messages.

Usage:
    check_attribution.py --msg-file PATH   one message (the commit-msg hook)
    check_attribution.py --history         every commit message reachable from HEAD (make check)

A message is rejected if it has:
  - a Co-Authored-By (or Assisted-by, Generated-by, Helped-by) trailer naming an AI
    tool or vendor,
  - the address noreply@anthropic.com anywhere,
  - a line that starts with "Generated with" or "Generated by" (after any emoji or
    punctuation),
  - the robot emoji U+1F916 anywhere.

In --msg-file mode, comment lines and everything below git's scissors line are ignored,
because git strips them before the commit is recorded.
"""

from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

from hygiene_common import report

ROBOT = chr(0x1F916)

AI_NAMES = re.compile(
    r"claude|anthropic|openai|chatgpt|\bgpt|copilot|gemini|\bbard\b|cursor|codeium|"
    r"windsurf|\bdevin\b|\baider\b|codex|tabnine|codewhisperer|amazon q\b|\bllama|"
    r"mistral|\bgrok\b|deepseek|qwen|perplexity|\bai\b|\bllm\b",
    re.IGNORECASE,
)
TRAILER = re.compile(
    r"^\s*(co-authored-by|assisted-by|generated-by|helped-by)\s*:(?P<who>.*)$",
    re.IGNORECASE,
)
GENERATED_LINE = re.compile(r"^\W*generated\s+(with|by)\b", re.IGNORECASE)
VENDOR_ADDRESS = "noreply@" + "anthropic.com"
SCISSORS = re.compile(r"^# -+ >8 -+$")


def problems_in(message: str) -> list[str]:
    found: list[str] = []
    for lineno, line in enumerate(message.splitlines(), start=1):
        trailer = TRAILER.match(line)
        if trailer and AI_NAMES.search(trailer.group("who")):
            found.append(f"line {lineno}: {trailer.group(1)} trailer names an AI tool")
        if VENDOR_ADDRESS in line.lower():
            found.append(f"line {lineno}: AI vendor noreply address")
        if GENERATED_LINE.match(line):
            found.append(f"line {lineno}: 'Generated with/by' attribution line")
        if ROBOT in line:
            found.append(f"line {lineno}: robot emoji")
    return found


def strip_git_comments(raw: str) -> str:
    kept: list[str] = []
    for line in raw.splitlines():
        if SCISSORS.match(line):
            break
        if line.startswith("#"):
            continue
        kept.append(line)
    return "\n".join(kept)


def history() -> list[tuple[str, str]]:
    has_head = subprocess.run(
        ["git", "rev-parse", "--verify", "--quiet", "HEAD"], capture_output=True
    )
    if has_head.returncode != 0:
        return []  # no commits yet
    out = subprocess.run(
        ["git", "log", "--format=%H%x00%B%x1e"], check=True, capture_output=True
    ).stdout.decode("utf-8", errors="replace")
    commits: list[tuple[str, str]] = []
    for record in out.split("\x1e"):
        record = record.lstrip("\n")
        if not record:
            continue
        sha, _, body = record.partition("\0")
        commits.append((sha, body))
    return commits


def main(argv: list[str]) -> int:
    problems: list[str] = []
    if len(argv) == 2 and argv[0] == "--msg-file":
        raw = Path(argv[1]).read_text(encoding="utf-8", errors="replace")
        problems = problems_in(strip_git_comments(raw))
    elif argv == ["--history"]:
        commits = history()
        for sha, body in commits:
            problems += [f"{sha[:12]} {p}" for p in problems_in(body)]
        if not problems:
            print(f"attribution guard: {len(commits)} commit message(s) clean")
    else:
        sys.exit("usage: check_attribution.py --msg-file PATH | --history")
    return report(
        problems,
        what="attribution guard",
        hint="Commit messages carry no AI-tool attribution. Remove those lines.",
    )


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
