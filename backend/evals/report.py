"""The eval table (architecture 18.7): docs/EVAL_TABLE.md and docs/eval_results.json.

`test_scenarios.py` records one `ScenarioResult` per scenario; at the end of the
session this plugin writes both files, but only when ERRAND_EVAL_REPORT_DIR is set
(`make evals` sets it through scripts/run_evals.py --write-report), so a filtered or
ad hoc run never overwrites the committed table. It refuses, and fails the session,
rather than write a table with no rows or without a row for a collected scenario.

The table carries only deterministic values: no latencies, and rows in scenario order.
A clean re-run produces the same bytes apart from the `Generated` timestamp in the
header (and the git SHA, when the commit changed). Nobody edits it by hand.
"""

from __future__ import annotations

import json
import os
import subprocess
from collections import Counter
from datetime import UTC, datetime
from pathlib import Path

import pytest

from errand.clock import wall_now
from evals.runner import ScenarioResult

REPORT_DIR_ENV = "ERRAND_EVAL_REPORT_DIR"
COLUMNS = ("scenario", "category", "model_mode", "world", "expected", "actual", "pass", "notes")
_results: list[ScenarioResult] = []
_seeds: dict[str, int] = {}
# SWEEP items, folded into one row at the end: seed -> (passed, outcome, rounds)
_sweep: dict[int, tuple[bool, str | None, int]] = {}
SWEEP = "SWEEP"


def record(result: ScenarioResult, seed: int) -> None:
    _results.append(result)
    _seeds[result.scenario] = seed


def record_sweep(seed: int, passed: bool, outcome: str | None, rounds: int) -> None:
    _sweep[seed] = (passed, outcome, rounds)


def sweep_row() -> ScenarioResult | None:
    """The one table row for every SWEEP item: `n_pass/N`."""
    if not _sweep:
        return None
    n = len(_sweep)
    ok = sum(1 for passed, _, _ in _sweep.values() if passed)
    ends = Counter(o for _, o, _ in _sweep.values())
    failed = sorted(s for s, (passed, _, _) in _sweep.items() if not passed)
    redrawn = sum(1 for _, _, rounds in _sweep.values() if rounds > 1)
    return ScenarioResult(
        scenario=SWEEP,
        category="booking_correctness",
        model_mode="scripted:reference + reader:keyword",
        world="default (70/15/7.5/7.5)",
        expected=(
            f"reference policy over seeds {min(_sweep)} to {max(_sweep)}: every invariant "
            "holds on every seed, each ends BOOKED_VERIFIED or PENDING_VERIFICATION"
        ),
        actual=(
            f"{ok}/{n} pass; BOOKED_VERIFIED={ends['BOOKED_VERIFIED']}, "
            f"PENDING_VERIFICATION={ends['PENDING_VERIFICATION']}; "
            f"{redrawn} seeds needed a second approval after slot_taken"
            + (f"; failed seeds {failed}" if failed else "")
        ),
        passed=ok == n,
        notes=f"seeds={min(_sweep)}-{max(_sweep)}; {ok}/{n}",
    )


def _git_sha(repo: Path) -> str:
    try:
        out = subprocess.run(
            ["git", "rev-parse", "--short=12", "HEAD"],
            cwd=repo,
            capture_output=True,
            text=True,
            timeout=10,
            check=True,
        )
    except (OSError, subprocess.SubprocessError):
        return "unknown"
    return out.stdout.strip()


def _cell(value: object) -> str:
    text = "pass" if value is True else "FAIL" if value is False else str(value)
    return text.replace("|", "\\|").replace("\n", " ")


def write_report(
    out_dir: Path, results: list[ScenarioResult], seeds: dict[str, int], now: datetime
) -> None:
    folded = sweep_row()
    if folded is not None:
        results = [*results, folded]
        seeds = {**seeds, SWEEP: min(_sweep), f"{SWEEP}-max": max(_sweep)}
    rows = sorted((r.row() for r in results), key=lambda r: str(r["scenario"]))
    sha = _git_sha(out_dir)
    seed_values = sorted(set(seeds.values()))
    seed_range = f"{seed_values[0]}-{seed_values[-1]}" if seed_values else "none"
    stamp = now.astimezone(UTC).strftime("%Y-%m-%dT%H:%M:%SZ")
    passed = sum(1 for r in rows if r["pass"])
    # scripted first, then the cassette-backed modes the rows actually use
    kinds = {str(r["model_mode"]).split(":")[0].split(" ")[0] for r in rows}
    modes = ", ".join(sorted(kinds, key=lambda k: (k != "scripted", k)))
    lines = [
        "# Eval table",
        "",
        "Generated by `make evals` from `backend/evals/scenarios/*.yaml`. Do not edit by hand.",
        "",
        f"- Generated: {stamp}",
        f"- Git SHA: {sha}",
        f"- Model mode: {modes}",
        f"- Seeds: {seed_range}",
        f"- Result: {passed}/{len(rows)} passed",
        "",
        "| " + " | ".join(COLUMNS) + " |",
        "|" + "---|" * len(COLUMNS),
    ]
    lines += ["| " + " | ".join(_cell(row[c]) for c in COLUMNS) + " |" for row in rows]
    (out_dir / "EVAL_TABLE.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    data = {
        "generated_at": stamp,
        "git_sha": sha,
        "model_mode": modes,
        "seeds": seed_range,
        "passed": passed,
        "total": len(rows),
        "results": rows,
    }
    (out_dir / "eval_results.json").write_text(
        json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )


def refusal(results: list[ScenarioResult], collected: list[str]) -> str | None:
    """Why the table must not be written, or None. An empty table, or one missing a
    scenario that was collected (it crashed before recording a row), would replace the
    committed ledger with something that looks green and proves less."""
    if not results and not _sweep:
        return "no scenario produced a row (empty or broken catalogue)"
    missing = sorted(
        set(collected) - {r.scenario for r in results} - ({SWEEP} if _sweep else set())
    )
    if missing:
        return "no row for " + ", ".join(missing)
    return None


def _collected_scenarios(session: pytest.Session) -> list[str]:
    ids: list[str] = []
    for item in session.items:
        callspec = getattr(item, "callspec", None)
        name = getattr(item, "originalname", None)
        if name == "test_scenario" and callspec is not None:
            ids.append(str(callspec.id))
        elif name == "test_sweep" and SWEEP not in ids:
            ids.append(SWEEP)
    return ids


def pytest_sessionfinish(session: pytest.Session, exitstatus: int) -> None:
    target = os.environ.get(REPORT_DIR_ENV)
    if not target:
        return
    problem = refusal(_results, _collected_scenarios(session))
    if problem is not None:
        reporter = session.config.pluginmanager.get_plugin("terminalreporter")
        message = f"eval report not written to {target}: {problem}"
        if reporter is not None:
            reporter.write_line(message, red=True, bold=True)
        if session.exitstatus == pytest.ExitCode.OK:
            session.exitstatus = pytest.ExitCode.TESTS_FAILED
        return
    write_report(Path(target), _results, _seeds, wall_now())
